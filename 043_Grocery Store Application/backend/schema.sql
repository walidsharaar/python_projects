-- Grocery Store Management System schema (PostgreSQL)
-- Safe to run more than once. Sample data lives in seed.sql.

-- Staff accounts. Admins manage everything; cashiers sell and view orders.
CREATE TABLE IF NOT EXISTS users (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'cashier')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    failed_logins INT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Unit of Measure (UOM)
CREATE TABLE IF NOT EXISTS uom (
    uom_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uom_name VARCHAR(45) NOT NULL UNIQUE
);

-- Products
CREATE TABLE IF NOT EXISTS products (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    uom_id INT NOT NULL,
    price_per_unit NUMERIC(10, 2) NOT NULL CHECK (price_per_unit >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_uom
        FOREIGN KEY (uom_id)
        REFERENCES uom(uom_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

-- Orders header
CREATE TABLE IF NOT EXISTS orders (
    order_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL DEFAULT 0.00 CHECK (total_price >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Order line items
CREATE TABLE IF NOT EXISTS order_details (
    order_detail_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    product_id INT NOT NULL,
    quantity NUMERIC(10, 2) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),     -- price_per_unit at time of order
    total_price NUMERIC(10, 2) NOT NULL CHECK (total_price >= 0),   -- quantity * unit_price
    CONSTRAINT fk_orders
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_products
        FOREIGN KEY (product_id)
        REFERENCES products(product_id)
        ON DELETE RESTRICT
);

-- Columns added after the first release (kept separate so existing databases are upgraded in place)
ALTER TABLE products ADD COLUMN IF NOT EXISTS icon VARCHAR(16);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS created_by INT REFERENCES users(user_id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_orders_created_by ON orders (created_by);
CREATE INDEX IF NOT EXISTS idx_products_uom_id ON products (uom_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON orders (created_at DESC, order_id DESC);
CREATE INDEX IF NOT EXISTS idx_order_details_order_id ON order_details (order_id);
CREATE INDEX IF NOT EXISTS idx_order_details_product_id ON order_details (product_id);
