"""Step 2a: profile the raw data. Look only, change nothing.

For every table the script answers:
    1. How big is it, and which columns does it have?
    2. Per column: data type, missing values, number of distinct values.
    3. Which columns could be the primary key?
    4. Are there fully duplicated rows?
    5. Which date range does it cover?
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUTPUT = ROOT / "docs" / "data_profile.md"

TABLES = {
    "leads": ("olist_marketing_qualified_leads_dataset.csv", ["first_contact_date"]),
    "deals": ("olist_closed_deals_dataset.csv", ["won_date"]),
    "sellers": ("olist_sellers_dataset.csv", []),
    "orders": ("olist_orders_dataset.csv", [
        "order_purchase_timestamp", "order_approved_at",
        "order_delivered_carrier_date", "order_delivered_customer_date",
        "order_estimated_delivery_date",
    ]),
    "order_items": ("olist_order_items_dataset.csv", ["shipping_limit_date"]),
    "customers": ("olist_customers_dataset.csv", []),
    "products": ("olist_products_dataset.csv", []),
    "payments": ("olist_order_payments_dataset.csv", []),
    "reviews": ("olist_order_reviews_dataset.csv", [
        "review_creation_date", "review_answer_timestamp",
    ]),
}
RELATIONSHIPS = [
    ("deals", "mql_id", "leads", "mql_id"),
    ("deals", "seller_id", "sellers", "seller_id"),
    ("order_items", "order_id", "orders", "order_id"),
    ("order_items", "seller_id", "sellers", "seller_id"),
    ("order_items", "product_id", "products", "product_id"),
    ("orders", "customer_id", "customers", "customer_id"),
    ("payments", "order_id", "orders", "order_id"),
    ("reviews", "order_id", "orders", "order_id"),
]


def load(name: str) -> pd.DataFrame:
    file_name, date_cols = TABLES[name]
    return pd.read_csv(RAW / file_name, parse_dates=date_cols)


def profile_columns(df: pd.DataFrame) -> pd.DataFrame:
    """One row per column: type, missing values, distinct values, example."""
    rows = []
    for col in df.columns:
        s = df[col]
        non_null = s.dropna()
        row = {
            "column": col,
            "dtype": str(s.dtype),
            "missing": int(s.isna().sum()),
            "missing_%": round(s.isna().mean() * 100, 1),
            "distinct": int(s.nunique()),
            "example": str(non_null.iloc[0])[:30] if len(non_null) else "",
            "min": "",
            "max": "",
        }
        # min / max only make sense for numbers and dates
        if pd.api.types.is_numeric_dtype(s) or pd.api.types.is_datetime64_any_dtype(s):
            row["min"] = str(s.min())[:19]
            row["max"] = str(s.max())[:19]
        rows.append(row)
    return pd.DataFrame(rows)


def key_candidates(df: pd.DataFrame) -> list[str]:
    """Columns that are complete and unique, so each could identify a row."""
    return [c for c in df.columns if df[c].notna().all() and df[c].is_unique]


def check_relationship(child, c_col, parent, p_col) -> dict:
    """How well does the child column match the parent column?"""
    child_keys = child[c_col].dropna()
    found = child_keys.isin(parent[p_col])
    # Cardinality: how many child rows belong to one parent value at most?
    max_children = int(child_keys.value_counts().max())
    return {
        "match_%": round(found.mean() * 100, 1),
        "orphans": int((~found).sum()),
        "max_rows_per_key": max_children,
    }


def to_markdown(df: pd.DataFrame) -> str:
    """Small markdown table writer, so we need no extra package."""
    header = "| " + " | ".join(df.columns) + " |"
    line = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([header, line, *body])


def main() -> None:
    tables = {name: load(name) for name in TABLES}
    md = ["# Data profile (raw data, unchanged)", "",
          "Generated by `src/profile_data.py`. Do not edit by hand.", ""]

    for name, df in tables.items():
        cols = profile_columns(df)
        keys = key_candidates(df)
        dup_rows = int(df.duplicated().sum())

        print(f"\n=== {name}: {len(df):,} rows x {df.shape[1]} columns ===")
        print(f"key candidates: {keys or 'none'} | fully duplicated rows: {dup_rows}")
        missing = cols[cols["missing"] > 0][["column", "missing", "missing_%"]]
        if len(missing):
            print("columns with missing values:")
            print(missing.to_string(index=False))

        md += [f"## {name}", "",
               f"- File: `{TABLES[name][0]}`",
               f"- Size: {len(df):,} rows x {df.shape[1]} columns",
               f"- Key candidates: {', '.join(keys) if keys else 'none'}",
               f"- Fully duplicated rows: {dup_rows}", "",
               to_markdown(cols), ""]

    rel_rows = []
    for c_name, c_col, p_name, p_col in RELATIONSHIPS:
        result = check_relationship(tables[c_name], c_col, tables[p_name], p_col)
        rel_rows.append({"from": f"{c_name}.{c_col}", "to": f"{p_name}.{p_col}", **result})
    rel = pd.DataFrame(rel_rows)

    print("\n=== Relationships ===")
    print(rel.to_string(index=False))
    md += ["## Relationships", "",
           "`match_%`: share of child values found in the parent table. "
           "`orphans`: values without a partner. "
           "`max_rows_per_key`: 1 means one-to-one, more means one-to-many.", "",
           to_markdown(rel), ""]

    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text("\n".join(md), encoding="utf-8")
    print(f"\nSaved: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
