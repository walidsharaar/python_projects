"""Step 9: analysis of the SIMULATED EventPro data (src/simulate.py).

Run from the project root (after python src\\simulate.py):
    python analysis\\07_simulated_eventpro.py

SYNTHETIC DATA. The numbers say nothing about Olist or Event Inc.
The script shows the methods the job needs where Olist has no data:
    1. Channels incl. GEO (AI referrals) and cost per booking
    2. Tracking incident: real change or broken tracking?
    3. Enterprise win/loss by industry, with a regression
    4. Loss reasons by industry
    5. Before/after: did automotive really get worse in H2 2025?
Writes reports/analysis/07_simulated_eventpro.md and data/results/sim_*.parquet.
"""

from pathlib import Path

import duckdb
import numpy as np
import pandas as pd
import statsmodels.formula.api as smf

from stats_utils import chi_square, evaluate_ab, rate_table, sample_size_per_group

ROOT = Path(__file__).resolve().parents[1]
DB_PATH = ROOT / "database" / "simulation.duckdb"
OUTPUT = ROOT / "reports" / "analysis" / "07_simulated_eventpro.md"
RESULTS = ROOT / "data" / "results"
BANNER = "> **SYNTHETIC DATA.** Generated by `src/simulate.py` with a planned story. Not Olist, not Event Inc."


def pct(x: float, digits: int = 1) -> str:
    return f"{x * 100:.{digits}f}%"


def p_text(p: float) -> str:
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


def channels(con, md: list) -> None:
    s = con.execute("SELECT * FROM sim_channel_summary").df()
    md += ["## 1. Channels 2025 vs 2024 (GEO and cost per booking)", "", "```text",
           f"  {'channel':<16}{'sessions':>10}{'YoY':>8}{'% sessions':>12}{'% bookings':>12}"
           f"{'bookings/1000 sessions':>24}{'cost/booking':>14}"]
    for r in s.itertuples():
        cost = f"{r.cost_per_booking_2025:,.0f} EUR" if pd.notna(r.cost_per_booking_2025) else "-"
        md.append(f"  {r.channel:<16}{r.sessions_2025:>10,.0f}{pct(r.sessions_yoy):>8}"
                  f"{pct(r.session_share_2025):>12}{pct(r.booking_share_2025):>12}"
                  f"{r.booking_per_session_2025 * 1000:>24.1f}{cost:>14}")
    md.append("```")

    ai = s.set_index("channel").loc["ai_referral"]
    org = s.set_index("channel").loc["organic_search"]
    test = evaluate_ab(int(org.bookings_2025), int(org.sessions_2025),
                       int(ai.bookings_2025), int(ai.sessions_2025))
    md += ["", f"- AI referrals: {pct(ai.session_share_2025)} of sessions but {pct(ai.booking_share_2025)} of bookings. "
               f"Bookings per session {test['rate_b'] / test['rate_a']:.1f}x organic search ({p_text(test['p_value'])}).",
           f"- Organic search sessions {pct(org.sessions_yoy)} vs 2024, AI referrals {pct(ai.sessions_yoy, 0)}. "
           "Part of the search demand moves into AI answers (GEO).",
           "- Cost per booking covers media spend only. It is not CAC (no salaries, tools, agency fees).", ""]



def tracking_incident(con, md: list) -> None:
    w = con.execute("SELECT * FROM sim_ai_referral_weekly ORDER BY week").df()
    # Expected share = median of the 8 weeks before; alarm if a week falls below half of it
    w["expected"] = w["ai_share"].shift(1).rolling(8).median()
    w["alarm"] = w["ai_share"] < 0.5 * w["expected"]
    alarms = w[w["alarm"]]
    md += ["## 2. Tracking check: real drop or broken tracking?", "",
           "Rule: alarm when the weekly AI-referral share falls below half of the median of the 8 weeks before.", "",
           "```text"]
    for r in alarms.itertuples():
        md.append(f"  week {r.week:%Y-%m-%d}: AI share {pct(r.ai_share)} (expected about {pct(r.expected)}), "
                  f"AI sessions {r.ai_sessions:,.0f}, direct {r.direct_sessions:,.0f}")
    md.append("```")
    found = set(alarms["week"].dt.date) == set(w.loc[w["is_incident"], "week"].dt.date)
    md += ["", f"- The rule finds {'exactly the' if found else 'NOT exactly the'} planned incident weeks (June 2025).",
           "- Signs of a tracking problem, not a demand problem: the drop is sudden, it starts on a release date, "
           "and it ends just as suddenly. Real demand changes are gradual.",
           "- Action: annotate the weeks in every report and do not use them for channel decisions.", ""]



def win_loss(con, md: list) -> None:
    deals = con.execute("""
        SELECT *, (status = 'won')::INT AS won,
               COALESCE(industry, 'unknown') AS industry_label,
               CASE WHEN first_response_hours <= 4 THEN 'a_under_4h'
                    WHEN first_response_hours <= 24 THEN 'b_4h_to_24h' ELSE 'c_over_24h' END AS response
        FROM sim_stg_crm_opportunities WHERE status <> 'open'
    """).df()
    chi2, dof, p = chi_square(deals, "industry_label", "won")
    table = rate_table(deals, "industry_label", "won", min_n=50)
    md += ["## 3. Enterprise win/loss", "",
           f"Decided deals: {len(deals):,} (open deals are left out: they are not decided yet). "
           f"Win rate {pct(deals['won'].mean())}.", "",
           f"Win rate by industry: chi2 = {chi2:.1f}, df = {dof}, {p_text(p)}", "", "```text"]
    for r in table.itertuples():
        md.append(f"  {r.industry_label:<20}{r.n:>6}{pct(r.rate):>8}   95% CI {pct(r.ci_low, 0)}-{pct(r.ci_high, 0)}"
                  f"{'  (small)' if r.small else ''}")
    md.append("```")
    overall = deals["won"].mean()
    above = [r.industry_label for r in table.itertuples() if r.ci_low > overall and not r.small]
    below = [r.industry_label for r in table.itertuples() if r.ci_high < overall and not r.small]
    md += ["", f"- Clearly above the average of {pct(overall)} (whole interval above it): {', '.join(above) or 'none'}. "
               f"Clearly below: {', '.join(below) or 'none'}. All other industries overlap the average and are not ranked."]

    model = smf.logit("won ~ C(industry_label, Treatment('finance_insurance')) + C(company_size, Treatment('250-999'))"
                      " + C(response) + C(event_type, Treatment('training'))", data=deals).fit(disp=False)
    ci = np.exp(model.conf_int())
    res = pd.DataFrame({"term": model.params.index, "odds_ratio": np.exp(model.params.values),
                        "ci_low": ci[0].values, "ci_high": ci[1].values, "p_value": model.pvalues.values})
    res = res[res["term"] != "Intercept"].copy()
    res["term"] = (res["term"].str.replace(r"C\((\w+).*?\)\[T\.", r"\1 = ", regex=True).str.rstrip("]")
                   .str.replace("industry_label", "industry"))
    RESULTS.mkdir(parents=True, exist_ok=True)
    res.to_parquet(RESULTS / "sim_winloss_regression.parquet", index=False)

    md += ["", f"Logistic regression (all attributes together). Reference: finance_insurance, 250-999 employees, "
               f"first answer under 4 h, training. n = {len(deals):,}, pseudo R2 = {model.prsquared:.3f}", "", "```text"]
    for r in res.itertuples():
        md.append(f"  {r.term:<34}{r.odds_ratio:>6.2f}   {r.ci_low:.2f}-{r.ci_high:.2f}   {p_text(r.p_value)}")
    md.append("```")
    slow = res.loc[res["term"] == "response = c_over_24h"].iloc[0]
    md += ["", f"- First answer after more than 24 h: odds of winning x{slow.odds_ratio:.2f}, even with industry, size "
               "and event type held constant. Still an association: maybe hard deals get slow answers.",
           "- Proof needs an experiment, e.g. a response-time rule (SLA) for half of the sales team first.", ""]



def loss_reasons(con, md: list) -> None:
    lr = con.execute("SELECT * FROM sim_loss_reasons").df()
    pivot = lr.pivot_table(index="loss_reason", columns="industry", values="share", fill_value=0)
    pivot = pivot.loc[pivot.mean(axis=1).sort_values(ascending=False).index]
    md += ["## 4. Loss reasons (share of each industry's lost deals)", "", "```text",
           pivot.map(lambda v: pct(v, 0)).to_string(), "```"]

    lost = con.execute("""
        SELECT industry = 'automotive' AS is_auto, (loss_reason = 'price')::INT AS is_price
        FROM sim_stg_crm_opportunities WHERE status = 'lost' AND loss_reason IS NOT NULL
    """).df()
    a, o = lost[lost.is_auto], lost[~lost.is_auto]
    t = evaluate_ab(int(o.is_price.sum()), len(o), int(a.is_price.sum()), len(a))
    missing = lr.loc[lr.loss_reason == "not_recorded", "lost_deals"].sum() / lr["lost_deals"].sum()
    md += ["", f"- Automotive loses on price in {pct(t['rate_b'], 0)} of lost deals vs {pct(t['rate_a'], 0)} "
               f"in other industries ({p_text(t['p_value'])}).",
           f"- {pct(missing)} of lost deals have no loss reason. Make the field required when a deal is closed as lost.", ""]



def before_after(con, md: list) -> None:
    """Did automotive get worse from 1 Jul 2025? Simple before/after per industry first,
    then difference-in-differences: automotive's change minus the change of all other
    industries in the same period. That removes effects that hit everyone (season, market)."""
    deals = con.execute("""
        SELECT COALESCE(industry, 'unknown') AS industry, (status = 'won')::INT AS won,
               (created_date >= DATE '2025-07-01')::INT AS after,
               COALESCE(industry = 'automotive', FALSE)::INT AS automotive   -- missing industry = not automotive
        FROM sim_stg_crm_opportunities WHERE status <> 'open'
    """).df()
    md += ["## 5. Before/after: did automotive get worse in H2 2025?", "",
           "Deals created before vs from 1 Jul 2025, decided deals only.", "", "```text"]
    for ind in ("automotive", "it_software", "pharma"):
        d = deals[deals.industry == ind]
        b, a = d[d.after == 0], d[d.after == 1]
        r = evaluate_ab(int(b.won.sum()), len(b), int(a.won.sum()), len(a))
        md.append(f"  {ind:<14} before {pct(r['rate_a'])} (n={len(b)})  after {pct(r['rate_b'])} (n={len(a)})  "
                  f"diff {r['diff'] * 100:+.1f} points, 95% CI {r['ci_low'] * 100:+.1f} to {r['ci_high'] * 100:+.1f}, "
                  f"{p_text(r['p_value'])}")
    md.append("```")

    others = deals[deals.automotive == 0]
    change_others = others[others.after == 1].won.mean() - others[others.after == 0].won.mean()
    auto = deals[deals.automotive == 1]
    change_auto = auto[auto.after == 1].won.mean() - auto[auto.after == 0].won.mean()
    did = smf.logit("won ~ automotive * after", data=deals).fit(disp=False)
    p_did = float(did.pvalues["automotive:after"])
    or_did = float(np.exp(did.params["automotive:after"]))
    md += ["", "Difference-in-differences (comparison group: all other industries):", "", "```text",
           f"  change automotive     {change_auto * 100:+.1f} points",
           f"  change other industries {change_others * 100:+.1f} points",
           f"  difference            {(change_auto - change_others) * 100:+.1f} points",
           f"  logistic regression interaction automotive x after: odds ratio {or_did:.2f}, {p_text(p_did)}", "```", ""]
    n_after = int(auto.after.sum())
    if p_did < 0.05:
        md += [f"- Confirmed: automotive fell more than the other industries in the same period ({p_text(p_did)}). "
               "Because the comparison group had the same season and market, the drop is specific to automotive.",
               f"- Still a small base ({n_after} decided automotive deals after 1 Jul 2025): the size of the drop is "
               "uncertain, the direction is not. The loss reasons (section 4) point to price."]
    else:
        md += [f"- Not confirmed: with {n_after} decided automotive deals after 1 Jul 2025 the difference to the "
               f"other industries could be chance ({p_text(p_did)}). Keep monitoring before acting.",
               "- Note: the generator does contain a drop (src/simulate.py). A real effect can stay invisible in a "
               "small sample."]
    md.append("")


def main() -> None:
    if not DB_PATH.exists():
        raise SystemExit("database/simulation.duckdb not found. Run python src\\simulate.py first.")
    md = ["# Evidence: simulated EventPro data (Step 9)", "", BANNER, "",
          "Generated by `analysis/07_simulated_eventpro.py`. Planned story and parameters: `docs/simulation.md`.", ""]
    with duckdb.connect(str(DB_PATH), read_only=True) as con:
        channels(con, md)
        tracking_incident(con, md)
        win_loss(con, md)
        loss_reasons(con, md)
        before_after(con, md)
    OUTPUT.write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    print(f"\nWritten: {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
